-- ============================================================================
--
-- ما هذا الملف؟
--   التصنيفات التي يبدأ بها كل عميل عند تسجيل مصروف.
--
-- لماذا هو ملف نظام (يُشغَّل تلقائيًا)؟
--   لأن شاشة المصروفات **تشترط اختيار تصنيف** قبل الحفظ. بلا هذه الصفوف يعجز
--   أي عميل جديد عن تسجيل مصروفه الأول، ويضطر لإنشاء تصنيف يدويًا قبل أن يعمل.
--
-- ── لماذا هذه التصنيفات عامة؟ ───────────────────────────────────────────────
--   الإيجار والرواتب والكهرباء والصيانة مصروفات موجودة في كل منشأة تقريبًا —
--   مطحنة كانت أو متجرًا أو صيدلية. وهي **نقطة بداية لا قيد**: العميل يضيف
--   تصنيفاته الخاصة أو يؤرشف ما لا يحتاجه من شاشة التصنيفات.
--
--   وقد استُبعدت التصنيفات الخاصة بنشاط بعينه (مثل «نخالة» أو «حبوب») لأنها
--   تخصّ عميلًا دون غيره.
--
-- ── علاقة التصنيف بالحساب المحاسبي ─────────────────────────────────────────
--   التصنيف **ليس** حسابًا محاسبيًا. التصنيف تنظيم إداري (كيف يصنّف المالك
--   مصروفه)، والحساب المحاسبي تحدّده دورة الترحيل. الفصل مقصود لسببين:
--     1. تصنيف واحد قد يُرحَّل إلى أكثر من حساب (إيجار المصنع والمكتب).
--     2. تعديل شجرة الحسابات يجب ألّا يغيّر تسميات المصروفات عند المالك.
--
-- ثابت (Idempotent): ON CONFLICT على (name).
-- المرجع: supabase/MIGRATIONS_RULES.md — القاعدة R-30.
-- ============================================================================

