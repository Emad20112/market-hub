  ('Packaging',   'تعبئة وتغليف',       60, true),
  ('Internet',    'اتصالات وإنترنت',    70, true),
  ('Office',      'مصروفات مكتبية',     80, true),
  ('Marketing',   'تسويق وإعلان',       90, true),
  ('Other',       'مصروفات أخرى',      100, true)
ON CONFLICT (name) DO NOTHING;

