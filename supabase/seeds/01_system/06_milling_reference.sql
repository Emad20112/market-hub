-- ============================================================================
-- 06_milling_reference.sql — مرجعيات وحدة الطحن
-- ============================================================================
--
-- ما هذا الملف؟
--   أنواع العبوات التي تفهمها وحدة الطحن في النظام.
--
-- لماذا هو ملف نظام (يُشغَّل تلقائيًا)؟
--   لأن وحدة الطحن تحلّ نوع العبوة **بالرمز** (`code`) لتحديد سلوكها: شوال
--   يُوزن، كيس يُعدّ. غياب الرمز يعطّل أوامر الطحن والتسليم.
--
-- ── الفرق بين نوع العبوة والعبوة نفسها ──────────────────────────────────────
--   هذا الجدول يعرّف **الأنواع** لا العبوات:
--       «شوال» و«كيس» نوعان عامّان تفهمهما الوحدة.
--
--   أما العبوة بأبعاد محدّدة — «شوال 50 كجم»، «كيس 10 كجم» — فهي **منتج**
--   تشتريه المنشأة وتبيعه، ومكانها كتالوج المنتجات في بيانات المنشأة.
--
--   وهذا هو الخطأ الذي كان في ملف الوحدات سابقًا: كان يضع «كيس 10 كجم» وحدةَ
--   قياس بينما هي عبوة بوزن محدّد.
--
-- ── ما ليس في هذا الملف ─────────────────────────────────────────────────────
--   درجات الحبوب (milling_grain_grades) — **ليست هنا عن قصد**:
--   ذلك الجدول يحمل مفتاحًا أجنبيًا إلى `products`، أي أن كل صف فيه يشير إلى
--   منتج حقيقي تشتريه منشأة بعينها. فهو بيانات منشأة، لا مرجع نظام.
--   مكانه: supabase/seeds/03_samples/sample-mill.sql
--
-- ثابت (Idempotent): ON CONFLICT على (code).
-- المرجع: supabase/MIGRATIONS_RULES.md — القاعدتان R-08 و R-30.
-- ============================================================================

BEGIN;

INSERT INTO public.packaging_types (code, name_ar, name_en, is_active, sort_order) VALUES
  ('SACK', 'شوال',  'Sack',  true, 1),
  ('BAG',  'كيس',   'Bag',   true, 2)
ON CONFLICT (code) DO NOTHING;

COMMIT;
