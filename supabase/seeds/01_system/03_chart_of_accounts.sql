-- ── التحقق بعد الإدخال ──────────────────────────────────────────────────────
-- نتأكد أن كل كود يستخدمه محرّك الترحيل موجود فعلًا. لو نقص حساب، يفشل الترحيل
-- لاحقًا برسالة غامضة، وهنا تظهر المشكلة قبل أن تحدث.
DO $$
DECLARE
  v_required text[] := ARRAY[
    '1101','1111',           -- النقدية والبنك
    '1211',                  -- ذمم العملاء
    '1311','1312','1313','1314','1315','1316',  -- المخزون وضريبة المدخلات
    '2111',                  -- ذمم الموردين
    '2311',                  -- ضريبة المخرجات
    '3111',                  -- رأس المال
    '4111','4211','4311',    -- الإيرادات
    '5111',                  -- تكلفة المبيعات
    '5911'                   -- المصروفات الأخرى والفاقد
  ];
  v_missing text[];
BEGIN
  SELECT array_agg(c) INTO v_missing
    FROM unnest(v_required) AS c
   WHERE NOT EXISTS (SELECT 1 FROM public.accounts a WHERE a.code = c);

  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION
      'حساب محاسبي مطلوب لم يُدرَج، وسيفشل الترحيل بدونه: %',
      array_to_string(v_missing, ', ');
  END IF;
END $$;

COMMIT;
