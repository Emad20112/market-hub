--                              '2111'                   -- ذمم الموردين
--       post_production_order  '1312'                   -- إنتاج تحت التنفيذ
--                              '5911'                   -- فاقد الإنتاج
--       post_opening_balance   '3111'                   -- رأس المال
--
--   أي حساب ناقص يجعل الترحيل يفشل برسالة:
--       «One or more account codes do not exist»
--
--   لذلك الأكواد هنا **عقد مع البرنامج** ولا يجوز تغييرها. أما الأسماء فهي
--   للقارئ، وقد صيغت بصيغة محايدة تصلح لأي منشأة.
--
-- ── قرار مهم: لماذا ليست الأسماء خاصة بمطحنة؟ ────────────────────────────────
--   كانت النسخة السابقة تحمل أسماء مطحنة بعينها:
--       «إيراد بيع الدقيق» · «إيراد بيع النخالة» · «إيراد أجور الطحن»
--       «أجهزة ومعدات المطحنة» · «مخزون دقيق» · «مخزون نواتج جانبية (نخالة)»
--       «البنك الأهلي اليمني» · «بنك مناحي كمر»
--
--   والمشكلة عملية: التطبيق موجَّه لكل المنشآت. من يفتح النظام لمتجر أو صيدلية
--   يرى حسابات مطحنة لا تخصّه.
--
--   الحل: **الأكواد ثابتة، والأسماء محايدة.** صاحب المطحنة يعيد التسمية من
--   شاشة دليل الحسابات إن أراد «إيراد بيع الدقيق»، أو يفتح حسابًا فرعيًا له.
--   النظام لا يتأثر لأن الكود لم يتغيّر.
--
-- ── ملاحظتان عن أعمدة خاصة ─────────────────────────────────────────────────
--   is_system = true       يكتب فيه محرّك الترحيل. لا يُحذف.
--   is_postable = false    حساب مقابل (contra). 1491 مجمع الإهلاك لا يُرحَّل
--                          إليه مباشرةً، بل عبر قيد الإهلاك فقط.
