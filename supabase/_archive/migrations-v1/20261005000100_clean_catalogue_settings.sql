-- تنظيف إعداد الفهرس في القاعدة
--
-- كان عمود catalog_modules يحمل قالباً كاملاً لمتجر قطع غيار
-- (بروفايل spare_parts مع توافق مركبات ودرجات جودة وبلدان منشأ
-- وماركات)، وهو ليس هذا النظام. الواجهة تتجاهل هذه المفاتيح الآن،
-- لكن بقاءها في القاعدة يعني أن أي تقرير أو تصدير يقرأها يرى
-- أبعاداً غير موجودة.
-- ═══════════════════════════════════════════════════════════════════

BEGIN;

UPDATE public.company_settings
   SET catalog_modules = '{"enableUnits": true, "enableGrainGrades": true, "enablePackagingBags": true}'::jsonb,
       updated_at = now()
 WHERE id = 1;

COMMIT;