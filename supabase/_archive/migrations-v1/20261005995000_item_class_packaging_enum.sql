-- إضافة قيمة PACKAGING إلى تصنيف الأصناف — ملف مستقل بقيمة واحدة
-- ============================================================================
-- WHY A SEPARATE FILE
-- -------------------
-- PostgreSQL لا يسمح باستخدام قيمة enum جديدة في *نفس المعاملة* التي أضافتها،
-- وSupabase يلفّ كل ملف ترحيل في معاملة واحدة. فوضعها مع بقية الإصلاح كان
-- سيُفشل كل شيء بخطأ «unsafe use of new value of enum type».
--
-- نفس النمط المعتمد في هذا المستودع: 20260801090000 يضيف قيمة وحده في أوله،
-- ثم يُستخدم الحدث في الملفات التالية.
--
-- WHY PACKAGING AT ALL
-- --------------------
-- كان التصنيف خماسياً بلا تعبئة، فأُجبرت الأكياس على الاختيار بين قيمتين
-- كلتاهما خطأ: NON_STOCK_ITEM (لا رصيد لها) أو FINISHED_GOOD (منتج للبيع).
-- والنتيجة أن 365 شوالاً لها رصيد فعلي في المخزون وهي مصنَّفة «غير مخزني».
--
-- PACKAGING تعني: شيء مادي يُشترى، يُخزَّن، ويُستهلك عند الاستخدام — لكنه ليس
-- منتجاً نهائياً للبيع في نقاط البيع.
-- ============================================================================

ALTER TYPE public.item_class ADD VALUE IF NOT EXISTS 'PACKAGING';

COMMENT ON TYPE public.item_class IS
  'تصنيف الصنف: خام / نهائي / جانبي / تعبئة / خدمة / غير مخزني. '
  'PACKAGING مميّز عن NON_STOCK_ITEM: التعبئة لها رصيد حقيقي يُشترى ويُستهلك.';
